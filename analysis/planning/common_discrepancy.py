"""Common-discrepancy Gaussian reference for the schizophrenia planning example.

Run from any directory with Python, NumPy, SciPy, and Matplotlib installed.
Inputs reproduce Section 6.1 / Web Appendix K. The discrepancy is constant,
delta = internal-control mean minus external-control mean. This analysis fixes
the population weights and variances; it is not a simulation of fitted AIPW-U.
"""

import csv
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np
from scipy.stats import norm

from planning_paths import output_dir

FIGURES = output_dir("figures")
TABLES = output_dir("tables")
CURVES = output_dir("curves")
VALIDATION = output_dir("validation")
ALPHA = 0.025
THETA_STAR = 2.0
R_SQUARED = 0.25
Z = float(norm.ppf(1 - ALPHA))
SCENARIOS = (
    {
        "scenario": "I",
        "sigma": 7.5,
        "treated": 120,
        "rct_controls": 120,
        "hct_controls": 60,
        "external_controls": 300,
    },
    {
        "scenario": "II",
        "sigma": 10.0,
        "treated": 120,
        "rct_controls": 120,
        "hct_controls": 60,
        "external_controls": 300,
    },
    {
        "scenario": "III",
        "sigma": 10.0,
        "treated": 240,
        "rct_controls": 240,
        "hct_controls": 120,
        "external_controls": 600,
    },
)
STYLES = {
    "HCT": ("#176CB0", "-"),
    "ECT": ("#D56713", (0, (5, 2.5))),
    "RCT ANCOVA": ("#8250A5", (0, (6, 2, 1.5, 2))),
}


def design_parameters(scenario):
    variance = (1 - R_SQUARED) * scenario["sigma"] ** 2
    n1, nc, ne, nr = (
        scenario[key]
        for key in ("treated", "hct_controls", "external_controls", "rct_controls")
    )
    share = nc / (nc + ne)
    assert np.isclose(share, 1 / 6, rtol=0, atol=1e-15)
    return {
        "HCT": (variance * (1 / n1 + 1 / (nc + ne)), 1 - share),
        "ECT": (variance * (1 / n1 + 1 / ne), 1.0),
        "RCT ANCOVA": (variance * (1 / n1 + 1 / nr), 0.0),
    }


def operating_characteristics(delta, sampling_variance, gap_multiplier):
    delta = np.asarray(delta)
    gap = gap_multiplier * delta
    se = np.sqrt(sampling_variance)
    standardized = gap / se
    return {
        "causal_gap": gap,
        "coverage": norm.cdf(Z - standardized) - norm.cdf(-Z - standardized),
        "null_rejection": norm.cdf(standardized - Z),
        "efficacy_declaration": norm.cdf((THETA_STAR + gap) / se - Z),
        "causal_mse": sampling_variance + gap**2,
        "interval_width": np.full_like(delta, 2 * Z * se),
    }


def write_csv(path, records):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=records[0].keys())
        writer.writeheader()
        writer.writerows(records)


def write_latex_table(endpoints):
    """Appendix table with zero-discrepancy calibration in the caption."""
    lines = [
        r"% Generated by analysis/planning/common_discrepancy.py; do not hand-edit numeric entries.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Known-input, fixed-weight Gaussian planning comparisons under a common constant source discrepancy. The displayed gap, coverage, and causal-null rejection use $\delta=.5$; causal mean squared error (MSE) is shown at $\delta=0$ and $.5$. At $\delta=0$, all gaps are zero, coverage is $.950$, and null rejection is $.025$. Interval width is constant across discrepancies. At $\delta=-.5$, coverage and MSE are unchanged, whereas null rejection and efficacy declaration differ with the sign of the gap, as shown in Figure~\ref{fig:commonsourcediscrepancy}. Scenarios and variances follow~\eqref{eq:studyvariances}.}",
        r"\label{tab:commondiscrepancy}",
        r"\renewcommand{\baselinestretch}{1}\fontsize{9.5}{11}\selectfont",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrrr@{}}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{$\delta=.5$} & \multicolumn{2}{c}{Causal MSE} & \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
        r"Scenario & Design & $\xi_{\lambda,\delta}$ & $\mathcal C(\xi_{\lambda,\delta})$ & $\mathcal R(\xi_{\lambda,\delta})$ & $\delta=0$ & $\delta=.5$ & 95\% width\\",
        r"\midrule",
    ]
    previous = None
    for record in endpoints:
        if record["source_discrepancy"] != 0.5:
            continue
        scenario = record["scenario"]
        if previous is not None and scenario != previous:
            lines.append(r"\addlinespace")
        name = scenario if scenario != previous else ""
        metrics = [
            record["causal_gap"],
            record["coverage"],
            record["null_rejection"],
            record["sampling_variance"],
            record["causal_mse"],
            record["interval_width"],
        ]
        values = [f"${value:.3f}$".replace("$0.", "$.") for value in metrics]
        values[0] = "$0$" if record["causal_gap"] == 0 else values[0]
        lines.append(" & ".join([name, record["design"], *values]) + r"\\")
        previous = scenario
    lines.extend([r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""])
    (TABLES / "common_discrepancy.tex").write_text("\n".join(lines), encoding="utf-8")


def main():
    delta = np.linspace(-0.5, 0.5, 1001)
    middle = len(delta) // 2
    curves, endpoints, comparisons = [], [], []
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 9.5,
            "axes.titlesize": 9.5,
            "axes.labelsize": 9.5,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "mathtext.fontset": "cm",
        }
    )
    fig, axes = plt.subplots(3, 3, figsize=(6.75, 6.15), sharex=True)
    fig.subplots_adjust(
        left=0.118, right=0.985, bottom=0.18, top=0.94, wspace=0.32, hspace=0.18
    )
    metrics = ("coverage", "null_rejection", "efficacy_declaration")
    for ax, title in zip(
        axes[0], ("Causal coverage", "Null rejection", "Efficacy declaration")
    ):
        ax.set_title(title, loc="left", fontweight="bold", pad=8)
    for row, scenario in enumerate(SCENARIOS):
        parameters = design_parameters(scenario)
        values_by_design = {}
        for design, (sampling_variance, multiplier) in parameters.items():
            values = operating_characteristics(delta, sampling_variance, multiplier)
            values_by_design[design] = values
            assert np.isclose(values["coverage"][middle], 0.95, rtol=0, atol=1e-14)
            assert np.isclose(
                values["null_rejection"][middle], ALPHA, rtol=0, atol=1e-14
            )
            assert np.allclose(
                values["coverage"], values["coverage"][::-1], atol=1e-14, rtol=0
            )
            assert np.all(np.diff(values["null_rejection"]) >= -1e-14)
            assert np.all(np.diff(values["efficacy_declaration"]) >= -1e-14)
            if design == "RCT ANCOVA":
                assert all(np.ptp(values[name]) == 0 for name in values)
            else:
                assert np.all(values["null_rejection"][middle + 1 :] > ALPHA)
            color, linestyle = STYLES[design]
            for column, metric in enumerate(metrics):
                axes[row, column].plot(
                    delta,
                    values[metric],
                    color=color,
                    linestyle=linestyle,
                    linewidth=1.35,
                    zorder=3,
                )
            for index, discrepancy in enumerate(delta):
                record = {
                    **scenario,
                    "design": design,
                    "source_discrepancy": float(discrepancy),
                    "sampling_variance": sampling_variance,
                    "standard_error": float(np.sqrt(sampling_variance)),
                    "gap_multiplier": multiplier,
                    **{name: float(value[index]) for name, value in values.items()},
                }
                curves.append(record)
                if index in (0, middle, len(delta) - 1):
                    endpoints.append(record)
        hct, ect = values_by_design["HCT"], values_by_design["ECT"]
        # Under a shared discrepancy and these counts, HCT reduces both variance
        # and absolute displacement relative to ECT. This is scenario specific.
        assert np.all(hct["coverage"] >= ect["coverage"] - 1e-14)
        assert np.all(hct["causal_mse"] < ect["causal_mse"])
        assert np.all(
            hct["null_rejection"][middle:] <= ect["null_rejection"][middle:] + 1e-14
        )
        for design in ("HCT", "ECT"):
            variance, multiplier = parameters[design]
            crossing = np.sqrt(parameters["RCT ANCOVA"][0] - variance) / multiplier
            comparisons.append(
                {
                    "scenario": scenario["scenario"],
                    "design": design,
                    "absolute_delta_at_equal_mse_to_rct_ancova": float(crossing),
                }
            )
        for col, ax in enumerate(axes[row]):
            ax.set_xlim(-0.52, 0.52)
            ax.set_xticks([-0.5, 0, 0.5], ["\u2212.5", "0", ".5"])
            ax.grid(color="#DFDFDF", linewidth=0.5)
            ax.set_axisbelow(True)
            ax.tick_params(length=2.5, width=0.6, pad=2)
            for spine in ax.spines.values():
                spine.set_color("#444444")
                spine.set_linewidth(0.6)
            if col == 0:
                ax.set_ylim(0.875, 0.958)
                ax.set_yticks([0.88, 0.90, 0.92, 0.95], [".88", ".90", ".92", ".95"])
            elif col == 1:
                ax.set_ylim(0, 0.125)
                ax.set_yticks(
                    [0, 0.025, 0.05, 0.075, 0.10], ["0", ".025", ".05", ".075", ".10"]
                )
            else:
                ax.set_ylim(0.3, 1.015)
                ax.set_yticks([0.4, 0.6, 0.8, 1.0], [".4", ".6", ".8", "1"])
                ax.axhline(
                    0.8,
                    color="#999999",
                    linewidth=0.65,
                    linestyle=(0, (4, 3)),
                    zorder=1,
                )
        bounds = axes[row, 0].get_position()
        fig.text(
            0.022,
            (bounds.y0 + bounds.y1) / 2,
            scenario["scenario"],
            ha="center",
            va="center",
            fontsize=10.5,
            fontweight="bold",
        )
    xlabel = fig.text(
        0.55,
        0.115,
        r"Common source discrepancy $\delta=m_{1,0}-m_0$",
        ha="center",
        fontsize=10,
    )
    labels = {
        "HCT": r"HCT: gap $5\delta/6$",
        "ECT": r"ECT: gap $\delta$",
        "RCT ANCOVA": "RCT ANCOVA: zero gap",
    }
    handles = [
        Line2D(
            [], [], color=color, linestyle=style, linewidth=1.35, label=labels[design]
        )
        for design, (color, style) in STYLES.items()
    ]
    legend = fig.legend(
        handles=handles,
        loc="lower center",
        bbox_to_anchor=(0.55, 0.045),
        ncol=3,
        frameon=False,
        fontsize=9.2,
        handlelength=2.1,
        columnspacing=0.9,
        handletextpad=0.5,
    )
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    for ax in axes.flat:
        box = ax.get_tightbbox(renderer)
        assert 0 <= box.x0 < box.x1 <= fig.bbox.width
        assert 0 <= box.y0 < box.y1 <= fig.bbox.height
        for line in ax.lines:
            assert np.all(np.asarray(line.get_ydata()) >= ax.get_ylim()[0])
            assert np.all(np.asarray(line.get_ydata()) <= ax.get_ylim()[1])
    for row in axes:
        for left, right in zip(row[:-1], row[1:]):
            assert left.get_tightbbox(renderer).x1 < right.get_tightbbox(renderer).x0
    for row in range(2):
        assert min(ax.get_tightbbox(renderer).y0 for ax in axes[row]) > max(
            ax.get_tightbbox(renderer).y1 for ax in axes[row + 1]
        )
    assert legend.get_window_extent(renderer).y1 < xlabel.get_window_extent(renderer).y0
    assert xlabel.get_window_extent(renderer).y1 < min(
        ax.get_tightbbox(renderer).y0 for ax in axes[-1]
    )
    fig.savefig(FIGURES / "common_source_discrepancy.pdf", facecolor="white")
    fig.savefig(FIGURES / "common_source_discrepancy.png", dpi=220, facecolor="white")
    plt.close(fig)
    write_csv(CURVES / "common_discrepancy.csv", curves)
    write_csv(TABLES / "common_discrepancy_endpoints.csv", endpoints)
    write_latex_table(endpoints)
    write_csv(TABLES / "mse_crossings.csv", comparisons)
    report = {
        "reference": "known-input fixed-weight Gaussian planning calculation",
        "not_a_fitted_AIPW_U_simulation": True,
        "alpha": ALPHA,
        "theta_star": THETA_STAR,
        "r_squared": R_SQUARED,
        "discrepancy_range": [-0.5, 0.5],
        "scenarios": list(SCENARIOS),
        "gap_mapping": {"HCT": "5 delta / 6", "ECT": "delta", "RCT": "0"},
        "checks": {
            "zero_discrepancy_coverage": 0.95,
            "zero_discrepancy_null_rejection": ALPHA,
            "coverage_symmetry": True,
            "rejection_monotonicity": True,
            "common_discrepancy_hct_vs_ect_comparisons": True,
            "figure_text_and_curves_within_bounds": True,
        },
        "figure_inches": [6.75, 6.15],
    }
    (VALIDATION / "common_discrepancy.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    print(FIGURES / "common_source_discrepancy.pdf")


if __name__ == "__main__":
    main()
